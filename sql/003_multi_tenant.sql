-- Tenants: companies, their people, and the isolation rule kept inside the database.
--
-- The rule is written once, as a row-level security policy, instead of as a
-- `WHERE company_id = ...` that every query has to remember. FORCE is needed
-- because the tables are owned by the application role: without it the owner
-- would silently bypass the policy.
--
-- The application sets the tenant once per connection:
--   SET app.company_id = '1';
-- and every read and write is then filtered by the database itself.

CREATE TABLE companies (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    slug       text        NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT companies_name_check CHECK (length(btrim(name)) > 0)
);

CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint      NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    email      text        NOT NULL UNIQUE,
    full_name  text        NOT NULL,
    role       text        NOT NULL DEFAULT 'reviewer',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_role_check CHECK (role IN ('owner', 'reviewer'))
);

-- Every business row now belongs to exactly one company.
ALTER TABLE suppliers       ADD COLUMN company_id bigint REFERENCES companies(id) ON DELETE CASCADE;
ALTER TABLE documents       ADD COLUMN company_id bigint REFERENCES companies(id) ON DELETE CASCADE;
ALTER TABLE deals           ADD COLUMN company_id bigint REFERENCES companies(id) ON DELETE CASCADE;
ALTER TABLE document_events ADD COLUMN company_id bigint REFERENCES companies(id) ON DELETE CASCADE;

