CREATE INDEX suppliers_company_idx       ON suppliers (company_id);
CREATE INDEX documents_company_idx       ON documents (company_id);
CREATE INDEX deals_company_idx           ON deals (company_id);
CREATE INDEX document_events_company_idx ON document_events (company_id);

-- Uniqueness is per company: two clients may hold the same invoice number from
-- the same supplier on the same day, and each client has its own supplier card.
DROP INDEX IF EXISTS documents_dedupe_key;
CREATE UNIQUE INDEX documents_dedupe_key ON documents (company_id, supplier_id, number, doc_date)
    WHERE supplier_id IS NOT NULL AND number IS NOT NULL AND doc_date IS NOT NULL;

DROP INDEX IF EXISTS suppliers_tax_id_key;
CREATE UNIQUE INDEX suppliers_tax_id_key ON suppliers (company_id, tax_id)
    WHERE tax_id IS NOT NULL;

-- The tenant of the current connection, empty when nobody set it.
CREATE FUNCTION app_company_id() RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT nullif(current_setting('app.company_id', true), '')::bigint
$$;

ALTER TABLE suppliers       ENABLE ROW LEVEL SECURITY;
ALTER TABLE suppliers       FORCE  ROW LEVEL SECURITY;
ALTER TABLE documents       ENABLE ROW LEVEL SECURITY;
ALTER TABLE documents       FORCE  ROW LEVEL SECURITY;
ALTER TABLE deals           ENABLE ROW LEVEL SECURITY;
ALTER TABLE deals           FORCE  ROW LEVEL SECURITY;
ALTER TABLE document_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_events FORCE  ROW LEVEL SECURITY;
ALTER TABLE document_items  ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_items  FORCE  ROW LEVEL SECURITY;
ALTER TABLE supplier_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE supplier_contacts FORCE  ROW LEVEL SECURITY;

CREATE POLICY suppliers_tenant ON suppliers
    USING (company_id = app_company_id())
    WITH CHECK (company_id = app_company_id());

CREATE POLICY documents_tenant ON documents
    USING (company_id = app_company_id())
    WITH CHECK (company_id = app_company_id());

CREATE POLICY deals_tenant ON deals
    USING (company_id = app_company_id())
    WITH CHECK (company_id = app_company_id());

CREATE POLICY document_events_tenant ON document_events
    USING (company_id = app_company_id())
    WITH CHECK (company_id = app_company_id());

-- Line items and contacts carry no company of their own: they inherit it from
-- the row they belong to, so the policy asks the parent table.
CREATE POLICY document_items_tenant ON document_items
    USING (EXISTS (SELECT 1 FROM documents d WHERE d.id = document_id))
    WITH CHECK (EXISTS (SELECT 1 FROM documents d WHERE d.id = document_id));

CREATE POLICY supplier_contacts_tenant ON supplier_contacts
    USING (EXISTS (SELECT 1 FROM suppliers s WHERE s.id = supplier_id))
    WITH CHECK (EXISTS (SELECT 1 FROM suppliers s WHERE s.id = supplier_id));

-- The platform layer stays visible to everyone: companies and their people are
-- what the application needs before it knows which tenant it is serving.
COMMENT ON TABLE companies IS 'Tenants. Read by the platform layer, not filtered by RLS.';
COMMENT ON TABLE users IS 'People of a company with their role. The reference target for edited_by.';
