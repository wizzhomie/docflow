-- Real authentication: a password hash on the person, a session per sign-in,
-- and a log of every attempt.
--
-- Notes on purpose:
--   * the password is stored as a scrypt hash — the algorithm ships with Python,
--     so the demo needs no extra dependency to hash a secret correctly;
--   * a session stores the SHA-256 of its token, not the token: a database dump
--     cannot be replayed as a cookie;
--   * a person with a Google account has no password at all — the column is
--     nullable, and a null hash means "Google only";
--   * auth_events is the audit trail an interviewer asks about: who tried,
--     from where, and whether it worked.

ALTER TABLE users ADD COLUMN password_hash text;
ALTER TABLE users ADD COLUMN google_sub text;
CREATE UNIQUE INDEX users_google_sub_key ON users (google_sub) WHERE google_sub IS NOT NULL;

CREATE TABLE sessions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash  text        NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    user_agent  text        NOT NULL DEFAULT '',
    ip          text        NOT NULL DEFAULT ''
);

CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_expiry_idx ON sessions (expires_at);

CREATE TABLE auth_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         timestamptz NOT NULL DEFAULT now(),
    email      text        NOT NULL DEFAULT '',
    method     text        NOT NULL,
    outcome    text        NOT NULL,
    ip         text        NOT NULL DEFAULT '',
    user_agent text        NOT NULL DEFAULT '',
    detail     text        NOT NULL DEFAULT '',
    CONSTRAINT auth_events_method_check CHECK (method IN ('password', 'google', 'demo')),
    CONSTRAINT auth_events_outcome_check CHECK (outcome IN ('ok', 'denied', 'throttled', 'error'))
);

CREATE INDEX auth_events_email_idx ON auth_events (email, at DESC);
